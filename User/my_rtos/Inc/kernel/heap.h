#pragma once

#include <stddef.h>

/* ==========================================================================
 * first-fit 空闲链表堆分配器
 *
 * 空闲块按地址升序串成一条链：
 *     head -> 空闲块 -> 空闲块 -> tail
 * 分配时从头找第一块足够大的；释放时按地址插回去，并尝试和前后相邻的
 * 空闲块合并。head / tail 是不占实际内存的哨兵，用来省掉边界判断。
 * ========================================================================== */

/* 建立初始空闲链表。第一次 HeapMalloc 会自动调用，不必手动调。 */
void HeapInit(void);

/* 分配 req_size 字节，失败返回 NULL。 */
void *HeapMalloc(size_t req_size);

/* 释放 HeapMalloc 返回的指针。 */
void HeapFree(void *ptr);
